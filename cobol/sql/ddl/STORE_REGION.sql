-- PRCDB.PRICE_REGION / PRCDB.STORE_REGION : pricing region reference data
-- Read-only for PRCUPD01 (store -> region resolution for store-level promos).
-- Demo stand-in : data/input/STORE_REGION.csv (weekly unload, job STRGNUNL)
-- DCLGEN        : cobol/copybooks/DCLSTRGN.cpy

CREATE TABLE PRCDB.PRICE_REGION
(
    REGION_CD       CHAR(2)        NOT NULL,
    REGION_NAME     VARCHAR(30)    NOT NULL,
    CONTIGUOUS_IND  CHAR(1)        NOT NULL WITH DEFAULT 'Y',
    CONSTRAINT PK_PRICE_REGION PRIMARY KEY (REGION_CD)
)
IN PRCDB.TSREF
CCSID EBCDIC;

