CREATE TABLE PRCDB.STORE_REGION
(
    STORE_NBR       CHAR(4)        NOT NULL,
    STORE_NAME      VARCHAR(30)    NOT NULL,
    STATE_CD        CHAR(2)        NOT NULL,
    REGION_CD       CHAR(2)        NOT NULL,
    OPEN_DT         DATE,
    CLOSE_DT        DATE,
    CONSTRAINT PK_STORE_REGION PRIMARY KEY (STORE_NBR),
    CONSTRAINT FK_STORE_REGION_RGN FOREIGN KEY (REGION_CD)
        REFERENCES PRCDB.PRICE_REGION (REGION_CD)
)
IN PRCDB.TSREF
CCSID EBCDIC;

CREATE INDEX PRCDB.XSTORE_REGION_01
    ON PRCDB.STORE_REGION (REGION_CD, STORE_NBR);

COMMENT ON TABLE PRCDB.STORE_REGION IS
    'Store to pricing-region mapping. Region NC (Alaska/Hawaii) carries freight uplift rules in PRCRGN01.';
